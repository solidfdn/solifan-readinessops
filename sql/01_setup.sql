-- ============================================================
-- READINESSOPS Setup: Database, Schema, and Table Definitions
-- ============================================================
-- Safe to run in any fresh Snowflake environment.
-- Uses CREATE ... IF NOT EXISTS to avoid overwriting existing data.
-- Run this script FIRST before seed data or views.
-- ============================================================

-- Database and schema
CREATE DATABASE IF NOT EXISTS READINESSOPS;
CREATE SCHEMA IF NOT EXISTS READINESSOPS.APP;

USE SCHEMA READINESSOPS.APP;

-- ============================================================
-- Tables
-- ============================================================

CREATE TABLE IF NOT EXISTS ASSESSMENT_RUNS (
    RUN_ID VARCHAR(16777216),
    RUN_NAME VARCHAR(16777216),
    ORGANIZATION_NAME VARCHAR(16777216),
    ASSESSMENT_SCOPE VARCHAR(16777216),
    STATUS VARCHAR(16777216),
    CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS READINESS_DOMAINS (
    DOMAIN_ID VARCHAR(16777216),
    DOMAIN_NAME VARCHAR(16777216),
    DOMAIN_DESCRIPTION VARCHAR(16777216),
    SORT_ORDER NUMBER(38,0)
);

CREATE TABLE IF NOT EXISTS READINESS_QUESTIONS (
    QUESTION_ID VARCHAR(16777216),
    DOMAIN_ID VARCHAR(16777216),
    QUESTION_TEXT VARCHAR(16777216),
    EXPECTED_EVIDENCE VARCHAR(16777216),
    WEIGHT NUMBER(38,0),
    SORT_ORDER NUMBER(38,0)
);

CREATE TABLE IF NOT EXISTS ASSESSMENT_ANSWERS (
    RUN_ID VARCHAR(16777216),
    QUESTION_ID VARCHAR(16777216),
    ANSWER_STATUS VARCHAR(16777216),
    ANSWER_TEXT VARCHAR(16777216),
    OWNER_NAME VARCHAR(16777216),
    UPDATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS EVIDENCE_ITEMS (
    EVIDENCE_ID VARCHAR(16777216),
    RUN_ID VARCHAR(16777216),
    QUESTION_ID VARCHAR(16777216),
    EVIDENCE_TITLE VARCHAR(16777216),
    EVIDENCE_TEXT VARCHAR(16777216),
    EVIDENCE_STATUS VARCHAR(16777216),
    CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS READINESS_GAPS (
    GAP_ID VARCHAR(16777216),
    RUN_ID VARCHAR(16777216),
    DOMAIN_ID VARCHAR(16777216),
    QUESTION_ID VARCHAR(16777216),
    GAP_TITLE VARCHAR(16777216),
    GAP_DESCRIPTION VARCHAR(16777216),
    SEVERITY VARCHAR(16777216),
    PRIORITY_SCORE NUMBER(38,0),
    CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RECOMMENDED_ACTIONS (
    ACTION_ID VARCHAR(16777216),
    RUN_ID VARCHAR(16777216),
    GAP_ID VARCHAR(16777216),
    ACTION_TITLE VARCHAR(16777216),
    ACTION_DESCRIPTION VARCHAR(16777216),
    OWNER_NAME VARCHAR(16777216),
    DUE_IN_DAYS NUMBER(38,0),
    ACTION_STATUS VARCHAR(16777216),
    CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS AGENT_RUN_HISTORY (
    AGENT_RUN_ID VARCHAR(16777216),
    RUN_ID VARCHAR(16777216),
    AGENT_STEP VARCHAR(16777216),
    INPUT_SUMMARY VARCHAR(16777216),
    OUTPUT_SUMMARY VARCHAR(16777216),
    CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);
