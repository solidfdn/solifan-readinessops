CREATE OR REPLACE VIEW APP_CODE.V_DECISION_PACK_REVIEW AS
SELECT
    p.PROPOSAL_ID,
    p.AGENT_RUN_ID,
    p.ASSESSMENT_RUN_ID,
    p.PROPOSAL_TYPE,
    p.TITLE,
    p.DESCRIPTION,
    p.SEVERITY,
    p.PRIORITY,
    p.RATIONALE,
    p.STATUS,
    p.PROPOSAL_PAYLOAD,
    p.CREATED_AT,
    p.UPDATED_AT
FROM APP_DATA.GOVERNANCE_AGENT_PROPOSAL p
WHERE p.PROPOSAL_TYPE IN (
    'DECISION_GOVERNANCE',
    'DECISION_VALUE',
    'DECISION_MODEL_ROUTING',
    'DECISION_PORTFOLIO'
);

CREATE OR REPLACE VIEW APP_CODE.V_AGENT_RUN_STEP AS
SELECT
    s.AGENT_RUN_ID,
    r.ASSESSMENT_RUN_ID,
    s.STEP_SEQUENCE,
    s.STEP_CODE,
    s.STEP_NAME,
    s.STATUS,
    s.STARTED_AT,
    s.COMPLETED_AT,
    s.DURATION_MS,
    s.STEP_DETAIL,
    s.ERROR_MESSAGE
FROM APP_DATA.GOVERNANCE_AGENT_RUN_STEP s
JOIN APP_DATA.GOVERNANCE_AGENT_RUN r
    ON r.AGENT_RUN_ID = s.AGENT_RUN_ID;

