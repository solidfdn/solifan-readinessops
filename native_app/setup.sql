-- Existing ReadinessOps presentation contracts over install-local state.
CREATE OR REPLACE VIEW APP_CODE.V_ASSESSMENT_CONTEXT AS
SELECT
    r.RUN_ID,
    r.RUN_NAME,
    r.ORGANIZATION_NAME,
    r.ASSESSMENT_SCOPE,
    r.STATUS,
    r.CREATED_AT,
    r.INITIATIVE_ID,
    i.INITIATIVE_NAME,
    i.DESCRIPTION AS INITIATIVE_DESCRIPTION,
    i.OWNER_NAME,
    i.LIFECYCLE_STAGE,
    i.BUSINESS_OUTCOME
FROM APP_DATA.ASSESSMENT_RUNS r
LEFT JOIN APP_DATA.AI_INITIATIVE i
    ON i.INITIATIVE_ID = r.INITIATIVE_ID;

CREATE OR REPLACE VIEW APP_CODE.V_EVIDENCE_ITEMS AS
SELECT
    EVIDENCE_ID,
    RUN_ID,
    QUESTION_ID,
    EVIDENCE_TITLE,
    EVIDENCE_TEXT,
    EVIDENCE_STATUS,
    SOURCE_TYPE,
    CONTENT_SHA256,
    SOURCE_REFERENCE,
    SOURCE_KEY_COLUMN,
    SOURCE_ROW_KEY,
    CREATED_AT,
    UPLOADED_AT,
    UPLOADED_BY
